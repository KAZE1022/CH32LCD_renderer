/*********************************************************************
 * File Name          : fps.h
 * Description        : FPS 统计 + 屏幕显示
 *
 *   用法(两步):
 *       LCD_Init();                 // 先初始化 LCD
 *       FPS_Init(1);                // 打开屏上显示(传 0 表示只统计不显示)
 *
 *       while (1)
 *       {
 *           ... 你的绘制代码 ...
 *           FPS_Tick();             // 每完成一帧调用一次
 *       }
 *
 *   工作原理:
 *      用 SysTick 计数器(24 位, 144MHz 下约 116ms 溢出一次)做微秒级计时,
 *      累计到 1 秒时算出 FPS 并刷新屏幕。
 *      为了支持 >1000 FPS 的情况, 统计窗口会逐档缩短:
 *          500ms -> 100ms -> 50ms -> 20ms
 *
 *   屏上显示内容(3 行 8x16 字符, 带背景条, 不会拖尾):
 *      FPS 60            当前帧率(窗口内平均)
 *      T  16MS           当前帧平均耗时
 *      R  58-61          窗口内最低/最高帧率
 *******************************************************************************/
#ifndef __FPS_H__
#define __FPS_H__

#include "debug.h"

/*---------------------------------------------------------------------------
 * 初始化 / 开关
 *-------------------------------------------------------------------------*/
/* 配置显示: x,y 是左上角坐标, 默认 (2,2); visible: 1=屏上显示 0=只统计 */
void FPS_Init(uint8_t visible);
void FPS_SetPosition(uint16_t x, uint16_t y);
void FPS_Show(uint8_t visible);

/*---------------------------------------------------------------------------
 * 每帧调用一次
 *-------------------------------------------------------------------------*/
void FPS_Tick(void);

/* 局部刷新时, 如果你的擦除/绘制区域可能压到 FPS 面板范围,
 * 就在每帧刷新完调用一次 FPS_CheckOverlap(刚擦/画的那块区域),
 * 面板会自动重画回来, 保证数字不被抹掉。不重叠时开销可忽略。 */
void FPS_CheckOverlap(uint16_t x, uint16_t y, uint16_t w, uint16_t h);

/* 强制重画面板(不管数值变没变)。
 * 用在"整屏被清掉"之后, 例如全屏刷新例程里每帧 LCD_Clear() 之后,
 * 不补画的话面板会被清屏抹掉。 */
void FPS_RedrawPanel(void);

/*---------------------------------------------------------------------------
 * 读取
 *-------------------------------------------------------------------------*/
uint16_t FPS_Get(void);              /* 当前 FPS(整数部分)          */
uint16_t FPS_GetX10(void);           /* 当前 FPS * 10 (保留 1 位小数) */
uint16_t FPS_GetFrameUs(void);       /* 当前帧平均耗时(微秒)        */
uint16_t FPS_GetMin(void);           /* 窗口内最低 FPS              */
uint16_t FPS_GetMax(void);           /* 窗口内最高 FPS              */
uint32_t FPS_GetTotalFrames(void);   /* 上电以来累计帧数            */

/* 清空统计(重新开始计数) */
void FPS_Reset(void);

/*---------------------------------------------------------------------------
 * 用 8x16 点阵在指定位置显示一个字符串(自带背景条, 不会拖尾)
 * 支持 0x20~0x5A: 空格 ! " # $ % & ' ( ) * + , - . / 0-9 : ; < = > ? @ A-Z
 * 返回占用宽度(像素)
 *-------------------------------------------------------------------------*/
uint16_t LCD_ShowSmallString(uint16_t x, uint16_t y, const char *str,
                             uint16_t color, uint16_t bgColor);

/* 屏上小字显示自检: 画纯色块 -> 画一行 "FPS 1.5 ..." -> 铺满整张 8x16 字符表
 * 如果连纯色块都看不见, 说明是 LCD 本身的问题, 不是 FPS 的问题 */
void FPS_Test(void);

#endif /* __FPS_H__ */
