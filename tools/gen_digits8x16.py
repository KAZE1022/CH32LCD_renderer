# 下面用函数拼装, 保证每个字形都是 16 行
def glyph(*rows):
    """统一排版: 上面留 2 行、下面留白, 使所有字符基线一致(笔画占 行2..行13)"""
    rows = list(rows)
    assert len(rows) <= 14, "字形笔画行数不能超过 14 行"
    return ['........', '........'] + rows + ['........'] * (14 - len(rows))

