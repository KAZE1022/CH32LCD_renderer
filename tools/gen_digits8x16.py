FIRST, LAST = 0x20, 0x5A


def main():
    preview = '--preview' in sys.argv
    here = os.path.dirname(os.path.abspath(__file__))
    out_file = os.path.join(here, '..', 'LCD', 'digits8x16.c')

    lines = []
    lines.append('/* 本文件由 tools/gen_digits8x16.py 生成，请勿手工修改')
    lines.append(' *')
    lines.append(" * 8x16 数字/字母点阵，覆盖范围 0x20(' ') ~ 0x5A('Z')")
    lines.append(' *   每个字符 16 字节，逐行，高位在左，1 表示有笔画')
    lines.append(' *   索引 = (字符编码 - 0x20) * 16')
    lines.append(' */')
    lines.append('#include "digits8x16.h"')
    lines.append('')
    count = LAST - FIRST + 1
    lines.append('const unsigned char Digits8x16[%d * 16] = {' % count)

    missing = 0
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        rows = G.get(ch)
        if rows is None:
            missing += 1
            rows = ['........'] * 16
        # 校验
        assert len(rows) == 16, "字形 '%s' 的行数是 %d, 应为 16" % (ch, len(rows))
        for r in rows:
            assert len(r) == 8, "字形 '%s' 有一行长度不是 8: %r" % (ch, r)

        if preview:
            print("--- 0x%02X '%s'" % (code, ch))
            for r in rows:
                print('  ' + r)

        name = "\\'" if ch == "'" else ch
        lines.append("    /* '%s' 0x%02X */" % (name, code))
        byte_vals = []
        for r in rows:
            v = 0
            for i in range(8):
                if r[i] == '#':
                    v |= 0x80 >> i
            byte_vals.append('0x%02X' % v)
        lines.append('    ' + ','.join(byte_vals) + ',')
    lines.append('};')

    with open(out_file, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')

    print('written %s (%d bytes), 字符数 %d, 缺失 %d'
          % (os.path.normpath(out_file), os.path.getsize(out_file), count, missing))


if __name__ == '__main__':
    main()
